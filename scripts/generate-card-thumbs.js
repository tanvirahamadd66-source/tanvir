/*
  Generates card-sized thumbnails for every image shown in a home-page project
  card (cover images, card slideshows, live-preview posters) and writes
  js/card-thumbs.js, which main.js uses to add a `srcset` so phones download
  and decode a ~1000px version instead of the 1600px original. Decoding all
  the full-size card images at once was a big part of the mobile out-of-memory
  crashes. Originals are untouched (project pages still use them).

  Usage (sharp is not a project dependency — run from a folder that has it):
    NODE_PATH=/path/with/node_modules node scripts/generate-card-thumbs.js
  Re-run after adding or changing any card image.
*/
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const sharp = require("sharp");

const ROOT = path.join(__dirname, "..");
const OUT_DIR = "assets/img/card-thumbs";
const THUMB_W = 1000;      // ~326px card × 3x phone screens
const TALL_THUMB_W = 700;  // tall panning posters (email designs) — width matters less

const ctx = {};
vm.createContext(ctx);
for (const f of ["js/projects-data.js", "js/behance-projects-data.js", "js/uiux-projects-data.js"]) {
  const code = fs.readFileSync(path.join(ROOT, f), "utf8").replace(/^\s*const\s+/gm, "var ");
  vm.runInContext(code, ctx);
}

const srcs = new Set();
for (const p of ctx.BEHANCE_PROJECTS || []) {
  if (p.cardSlides && p.cardSlides.length > 1) p.cardSlides.forEach((s) => srcs.add(s.src));
  else if (!p.livePreview) srcs.add(p.coverImage || p.gallery[0]);
  if (p.livePoster) srcs.add(p.livePoster);
}
for (const p of ctx.UIUX_PROJECTS || []) { if (p.image) srcs.add(p.image); if (p.livePoster) srcs.add(p.livePoster); }
for (const p of ctx.FEATURED_PROJECTS || []) if (p.image) srcs.add(p.image);

(async () => {
  const map = {};
  for (const src of srcs) {
    const abs = path.join(ROOT, src);
    if (!fs.existsSync(abs)) { console.warn("missing:", src); continue; }
    const meta = await sharp(abs).metadata();
    const tall = meta.height > meta.width * 2.5;
    const target = tall ? TALL_THUMB_W : THUMB_W;
    if (meta.width <= target * 1.15) continue; // already small enough
    const rel = path.posix.join(OUT_DIR, src.replace(/^assets\/img\//, "").replace(/\.[a-z]+$/i, ".webp"));
    fs.mkdirSync(path.join(ROOT, path.dirname(rel)), { recursive: true });
    await sharp(abs).resize({ width: target }).webp({ quality: 82 }).toFile(path.join(ROOT, rel));
    map[src] = [rel, target, meta.width];
  }
  const js = "/* Generated by scripts/generate-card-thumbs.js — do not edit by hand.\n" +
    "   original src -> [thumbnail src, thumbnail width, original width] */\n" +
    "const CARD_THUMBS = " + JSON.stringify(map, null, 2) + ";\n";
  fs.writeFileSync(path.join(ROOT, "js/card-thumbs.js"), js);
  console.log("thumbnails:", Object.keys(map).length, "of", srcs.size, "card images");
})();
